"""Build a Gazebo cloud-pack topology from P1's map plus its planning overlay.

P1's files are read, never edited. The overlay says what each node is for the
planner (kind, area, label, beds...); its fields go on top of P1's node. Aliases
are the overlay's plus the ones P1 declares in scenario_locations.json (their
logical ward and store names; a bed is not a node, so bed aliases are skipped).
Speed caps and edge weights stay P1's. Re-run after P1 updates their map:

    python scripts/build_sim_topology.py
    python scripts/build_sim_topology.py --pack hospital_sim6
"""

from __future__ import annotations

import json
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PACK = "hospital_sim"
NOTE = ("GENERATED by scripts/build_sim_topology.py from {base} and {overlay}. "
        "Do not edit by hand: change the overlay and rebuild.")


def pack_paths(pack: str = DEFAULT_PACK) -> tuple[Path, Path]:
    root = ROOT / "packs" / pack
    return root / "overlay.json", root / "topology.json"


def build(overlay_path: Path | None = None) -> dict:
    overlay_path = overlay_path or pack_paths()[0]
    overlay = json.loads(Path(overlay_path).read_text(encoding="utf-8"))
    base = json.loads((ROOT / overlay["base"]).read_text(encoding="utf-8"))
    missing = sorted(set(overlay["nodes"]) - set(base["nodes"]))
    if missing:
        raise ValueError(f"overlay names nodes that are not in {overlay['base']}: {missing}")
    p1_aliases = _p1_aliases(overlay, base)
    wp_path = (ROOT / overlay["base"]).with_name("topology_waypoints.json")   # P1's world coordinates, for the map view
    waypoints = json.loads(wp_path.read_text(encoding="utf-8"))["waypoints"] if wp_path.exists() else {}
    nodes = {}
    for nid, attrs in base["nodes"].items():
        node = {**attrs, **overlay["nodes"].get(nid, {})}
        if nid in waypoints:
            node["pos"] = waypoints[nid]
        names = _dedupe([*node.get("aliases", []), *p1_aliases.get(nid, [])])
        if names:
            node["aliases"] = names
        nodes[nid] = node
    return {
        "version": overlay["version"],
        "note": NOTE.format(base=overlay["base"], overlay=overlay_path.relative_to(ROOT)),
        "nodes": nodes,
        "edges": base["edges"],
        "clusters": overlay["clusters"],
    }


def _p1_aliases(overlay: dict, base: dict) -> dict:
    """node id -> the names P1's scenario_locations.json gives it (not beds)."""
    if "locations" not in overlay:
        return {}
    doc = json.loads((ROOT / overlay["locations"]).read_text(encoding="utf-8"))
    out: dict = {}
    for stable_id, loc in doc["locations"].items():
        if loc.get("logical_kind") == "bed":
            continue
        node = loc["physical_node"]
        if node not in base["nodes"]:
            raise ValueError(f"{overlay['locations']}: {stable_id} names unknown node {node!r}")
        out.setdefault(node, []).extend([stable_id, *loc.get("aliases", [])])
    return out


def _dedupe(names: list) -> list:
    seen, out = set(), []
    for n in names:
        if n.lower() not in seen:
            seen.add(n.lower())
            out.append(n)
    return out


def render(doc: dict) -> str:
    return json.dumps(doc, indent=2, sort_keys=True) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--pack", default=DEFAULT_PACK, help="Gazebo pack whose overlay and topology to rebuild")
    args = parser.parse_args()
    overlay, output = pack_paths(args.pack)
    output.write_text(render(build(overlay)), encoding="utf-8")
    print(f"wrote {output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
